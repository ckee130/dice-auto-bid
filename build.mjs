/**
 * Compiles the app's generation code into the extension.
 *
 * Run with: node dice-apply-bot/build.mjs
 *
 * The output is committed. An extension that needed a build step before it
 * would load is an extension that cannot simply be copied to a machine and
 * turned on, which is the whole point of it standing alone - so the bundle
 * ships, and this script exists to refresh it when the app changes.
 */

import { build } from "esbuild";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { statSync } from "node:fs";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "src/vendor/generation.js");

await build({
  entryPoints: [join(HERE, "vendor-entry.ts")],
  outfile: OUT,
  bundle: true,
  format: "esm",
  // A service worker, so: no DOM, and a Chrome new enough to be the one the
  // extension is loaded into.
  platform: "browser",
  target: "chrome120",
  legalComments: "none",
  // The app reads these to point at a mock provider during its own tests.
  // Undefined here, which falls through to each provider's real endpoint.
  define: {
    "process.env.OPENAI_BASE_URL": "undefined",
    "process.env.ANTHROPIC_BASE_URL": "undefined",
    "process.env.GOOGLE_BASE_URL": "undefined",
  },
  banner: {
    js: "/* Generated by dice-apply-bot/build.mjs from the app's src/lib. Do not edit. */",
  },
});

console.log(`Wrote ${OUT} (${Math.round(statSync(OUT).size / 1024)} KB)`);
